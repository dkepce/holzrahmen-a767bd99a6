"""Reads the Reuse Woodhouse workbook (sheet 'Wände') and writes js/catalog.js.
Run:  python tools/export_waende.py "<path to 24-09-23_Datenbank_ReuseWoodhouse.xlsx>"
The workbook is only read. Column letters follow row 5 of the sheet (see README)."""
import sys, json, re, datetime
import openpyxl
from openpyxl.utils import column_index_from_string as C

sys.stdout.reconfigure(encoding="utf-8")
src = sys.argv[1]
wb = openpyxl.load_workbook(src, data_only=True)
ws = wb["Wände"]

def raw(r, col):
    v = ws.cell(r, C(col)).value
    if isinstance(v, str):
        v = v.strip()
        if v == "": return None
    return v

def num(r, col):
    v = raw(r, col)
    if isinstance(v, (int, float)): return round(float(v), 3)
    if isinstance(v, str):
        m = re.fullmatch(r"-?\d+(?:[.,]\d+)?", v)
        if m: return round(float(v.replace(",", ".")), 3)
    return None

def txt(r, col):
    v = raw(r, col)
    if v is None: return None
    if isinstance(v, float) and v.is_integer(): v = int(v)
    return str(v)

def opening(r, c0, n):
    """c0 = column letter of 'Typ' of this Aussparung; the others follow in a fixed pattern."""
    i = C(c0)
    L = lambda k: openpyxl.utils.get_column_letter(i + k)
    typ = txt(r, L(0))
    if typ is None or typ.lower() == "x": return None
    pair = lambda k: ({"b": num(r, L(k)), "h": num(r, L(k + 1))} if (num(r, L(k)) is not None or num(r, L(k + 1)) is not None) else None)
    return {
        "n": n, "typ": typ, "teilung": num(r, L(1)), "mat": txt(r, L(2)), "sun": txt(r, L(3)), "uw": num(r, L(4)),
        "bA": num(r, L(5)), "hP": num(r, L(6)), "hST": num(r, L(7)),
        "AL": pair(8), "DL": pair(10), "RBL": pair(12), "note": txt(r, L(14)),
    }

out = []
for r in range(7, 223):
    if not ws.cell(r, 1).value: continue
    ops = [o for o in (opening(r, "AS", 1), opening(r, "BH", 2), opening(r, "BW", 3)) if o]
    w = {
        "id": txt(r, "A"), "year": num(r, "C"), "maker": txt(r, "D"), "plan": txt(r, "E"), "approval": txt(r, "F"),
        "cls": txt(r, "G"), "bw": txt(r, "H"), "kA": txt(r, "I"), "fas": txt(r, "J"), "kI": txt(r, "K"), "bepl": txt(r, "L"),
        "q": txt(r, "M"), "special": txt(r, "N"),
        "b": num(r, "O"), "h": num(r, "P"),
        "dbi": num(r, "Q"), "bepI": txt(r, "R"), "dp": num(r, "S"), "dba": num(r, "T"), "bepA": txt(r, "U"),
        "dRges": num(r, "V"), "bp": num(r, "W"), "ap": num(r, "X"), "apRaw": txt(r, "X"),
        "di": num(r, "Y"), "da": num(r, "Z"), "dges": num(r, "AA"),
        "aufbau": txt(r, "AB"), "dataholz": txt(r, "AC"),
        "U": num(r, "AD"), "m": num(r, "AE"), "REI": txt(r, "AF"), "RW": txt(r, "AG"), "load": num(r, "AH"),
        "L": {"typ": txt(r, "AI"), "b": num(r, "AJ"), "a": num(r, "AK")},
        "R": {"typ": txt(r, "AL"), "b": num(r, "AM"), "a": num(r, "AN")},
        "O": {"typ": txt(r, "AO"), "h": num(r, "AP")},
        "Un": {"typ": txt(r, "AQ"), "h": num(r, "AR")},
        "ops": ops, "desc": txt(r, "CL"), "row": r,
    }
    out.append(w)

hdr = "/* GENERATED by tools/export_waende.py from the Reuse Woodhouse workbook (sheet Wände). Do not edit by hand. */\n"
body = "window.APP = window.APP || {};\nAPP.CATALOG = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
body += "APP.CATALOG_INFO = " + json.dumps({"source": src.replace("\\", "/").split("/")[-1], "exported": datetime.date.today().isoformat(), "count": len(out)}) + ";\n"
open("js/catalog.js", "w", encoding="utf-8").write(hdr + body)
print(len(out), "walls written;", sum(len(w["ops"]) for w in out), "openings")
